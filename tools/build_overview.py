def strata_svg(w, h, bands, cls):
    import math
    paths = []
    for y, a, ph, c in bands:
        pts = ' L'.join(f'{x} {y + a * math.sin(2 * math.pi * x / 900 + ph):.1f}' for x in range(0, w + 1, 24))
        paths.append(f'<path d="M{pts} L{w} {h} L0 {h} Z" fill="{c}"/>')
    return f'<svg class="{cls}" aria-hidden="true" viewBox="0 0 {w} {h}" preserveAspectRatio="none">{"".join(paths)}</svg>'


