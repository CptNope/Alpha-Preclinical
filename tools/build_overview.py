def build_design_system():
    tokens = json.loads((DS / 'tokens.json').read_text())
    readme = (DS / 'README.md').read_text()
    toc = [('principles', 'Principles'), ('colour', 'Colour'), ('type', 'Type'), ('spacing', 'Spacing and radius'), ('components', 'Components'), ('files', 'Files')]

    # principles: README sections without the long tables
    intro_md = readme.split('## Colour')[0]
    intro_md = re.sub(r'^# .*\n', '', intro_md)
    principles = section('principles', 'Principles', f'<div class="ov-prose">{md(intro_md)}</div>')

    rows = []
    for t in tokens['color']['tokens']:
        light = t['value']['light'] if isinstance(t['value'], dict) else t['value']
        rows.append(f'<tr><td><span class="ov-chip" style="background:{light}"></span></td><td><code>{t["name"]}</code></td><td><code>{light}</code></td><td>{E(t["usage"])}</td></tr>')
    colour = section('colour', 'Colour', '<div class="ov-table"><table><thead><tr><th scope="col"><span class="screen-reader-text">Swatch</span></th><th scope="col">Token</th><th scope="col">Hex</th><th scope="col">Use</th></tr></thead><tbody>' + ''.join(rows) + '</tbody></table></div>',
                     'Use colours by role, not by taste. Every text pair meets WCAG AA.')

    specimens = []
    for g in tokens['type']['groups']:
        fam = 'var(--font-display)' if g['family'] == 'display' else 'var(--font-sans)'
        for s in g['styles']:
            sample = s.get('sample', 'Tailored in vivo research')
            style = f'font-family:{fam};font-size:{s["fontSize"]};line-height:{s["lineHeight"]};font-weight:{s["fontWeight"]};letter-spacing:{s.get("letterSpacing", "0")}'
            specimens.append(f'<div class="ov-spec"><p class="ov-spec__meta"><code>{s["name"]}</code> {s["fontSize"]} / {s["lineHeight"]} · {s["fontWeight"]}</p><p class="ov-spec__sample" style="{style}">{E(sample)}</p><p class="ov-spec__use">{E(s.get("usage", ""))}</p></div>')
    typ = section('type', 'Type', ''.join(specimens), 'Bricolage Grotesque 600 for headings, Figtree 400–600 for everything else. Both are self-hosted woff2 files.')

    sp = ''.join(f'<li><span class="ov-bar-sample" style="width:{t["value"]}"></span><code>{t["name"]}</code> {t["value"]} · {E(t["usage"])}</li>' for t in tokens['spacing']['tokens'])
    rd = ''.join(f'<li><span class="ov-radius" style="border-radius:{t["value"]}"></span><code>{t["name"]}</code> {t["value"]} · {E(t["usage"])}</li>' for t in tokens['radius']['tokens'])
    sh = ''.join(f'<li><span class="ov-radius" style="box-shadow:{t["value"]};border-color:transparent"></span><code>{t["name"]}</code> · {E(t["usage"])}</li>' for t in tokens.get('shadow', {}).get('tokens', []))
    spacing = section('spacing', 'Spacing, radius and shadow', f'<ul class="ov-samples">{sp}</ul><ul class="ov-samples ov-samples--row">{rd}{sh}</ul>')

    comps = []
    for d in sorted((DS / 'components').iterdir()):
        if not d.is_dir() or d.name == 'Cover' or not (d / 'preview.html').exists():
            continue
        prev = (d / 'preview.html').read_text().split('\n', 1)[1]
        prev = prev.replace('../../../../assets/', '../assets/')
        prev = re.sub(r'<(/?)h([12])\b', lambda m: f'<{m.group(1)}h4', prev)
        guide = (d / 'README.md').read_text() if (d / 'README.md').exists() else ''
        guide = re.sub(r'^# .*\n', '', guide)
        comps.append(f'<article class="ov-comp" id="c-{d.name.lower()}"><h3>{d.name}</h3><div class="ov-comp__stage">{prev}</div><div class="ov-prose">{md(guide)}</div></article>')
    components = section('components', 'Components', ''.join(comps), 'Live examples with their guidelines. The WordPress theme implements each as a block or block style.')

    files = section('files', 'Files', md(
        '- `design/design-system/tokens.json`: every token, with a usage note\n'
        '- `design/design-system/README.md`: the brand book text this page is built from\n'
        '- `design/design-system/components/`: one folder per component (preview + guidelines), plus `components.css`\n'
        '- `design/design-system/fonts/`: Bricolage Grotesque 600 and Figtree 400, 400 italic, 500, 600 (woff2)\n'
        '- `wordpress/alpha-preclinical/theme.json`: the same tokens as WordPress presets'))
    return page('design-system.html', 'Design system', 'The tokens, type and components behind the site, the WordPress theme and the brand book.',
                principles + colour + typ + spacing + components + files, toc)


