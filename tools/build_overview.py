def artboard(name):
    src = (BB / f'{name}.dc.html').read_text()
    inner = src.split('<x-dc>', 1)[1].split('</x-dc>', 1)[0]
    inner = re.sub(r'<helmet>.*?</helmet>', '', inner, flags=re.S)
    inner = inner.replace('../../assets/', '../assets/')
    # Shown inside a page that has its own H1/H2: drop the artboard's headings two levels.
    inner = re.sub(r'<(/?)h([12])\b', lambda m: f'<{m.group(1)}h{int(m.group(2)) + 2}', inner)
    links = {'BusinessCardFront.dc.html': '#cards', 'Letterhead.dc.html': '#letterhead', 'EmailSignature.dc.html': '#email',
             'LinkedInCompanyBanner.dc.html': '#linkedin', 'LinkedInProfileBanner.dc.html': '#linkedin', 'LinkedInPublication.dc.html': '#linkedin-posts'}
    for k, v in links.items():
        inner = inner.replace(f'href="{k}"', f'href="{v}"')
    m = re.search(r'"\$preview":\{"width":(\d+),"height":(\d+)\}', src)
    return inner.strip(), int(m.group(1)), int(m.group(2))


def frame(name, label, note='', maxw=None):
    inner, w, h = artboard(name)
    mw = f' style="max-width:{maxw}px"' if maxw else ''
    return (f'<figure class="ov-frame"{mw}><div class="ov-frame__fit" data-w="{w}" data-h="{h}" style="aspect-ratio:{w}/{h}">'
            f'<div class="ov-frame__art" style="width:{w}px;height:{h}px">{inner}</div></div>'
            f'<figcaption><b>{E(label)}</b> · {w} × {h} px{" · " + note if note else ""}</figcaption></figure>')


